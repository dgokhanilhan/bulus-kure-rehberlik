// Sınıflar → Sınıf analizi: tek tuşla şubenin bütün süreci, sıralama, bulgular, ortak konular ve PDF.
import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { DEMO, login, service, shot } from './helpers'

test('sınıf analizi: özet, sıralı öğrenci tablosu, süzgeç, deneme deneme sıra, PDF; geri tuşu Sınıflar', async ({ page }) => {
  test.setTimeout(90_000)
  const svc = service()
  const { data: cls } = await svc.from('students').select('id').eq('class_name', '8/B').is('archived_at', null)
  await login(page, ...DEMO.rehber)
  await page.getByRole('link', { name: 'Sınıflar', exact: true }).click()
  await expect(page.locator('#clsPick').or(page.getByRole('group', { name: 'Şube' }))).toBeVisible()
  if (await page.locator('#clsPick').count()) await page.locator('#clsPick').selectOption('8/B')
  else await page.getByRole('group', { name: 'Şube' }).getByRole('button', { name: '8/B' }).click()
  await page.getByRole('button', { name: 'Sınıf analizi' }).click()
  await expect(page).toHaveURL(/gorunum=analiz/)
  await expect(page.getByRole('heading', { name: '8/B · Sınıf analizi' })).toBeVisible()
  await expect(page.getByTestId('sinif-ozet')).toContainText('Katılım')
  const rows = page.getByTestId('sinif-satir')
  await expect(rows).toHaveCount(cls!.length)
  // Varsayılan sıra: son denemedeki sıra (1. en üstte)
  await expect(rows.first().locator('td').first()).toContainText('1.')
  // Ada göre sırala
  await page.getByRole('button', { name: 'Öğrenci', exact: true }).click()
  const names = await rows.locator('td:nth-child(2) b').allInnerTexts()
  expect(names).toEqual([...names].sort((a, b) => a.localeCompare(b, 'tr')))
  // Süzgeç: "Hepsi" + sayılar
  await expect(page.getByRole('group', { name: 'Süzgeç' }).getByRole('button', { name: /^Hepsi \(\d+\)$/ })).toHaveAttribute('aria-pressed', 'true')
  // Deneme deneme netler açık gelir: her öğrenci + sınıf ortalaması satırı; hücrelerde net yazar
  await expect(page.getByTestId('sira-tablo').locator('tbody tr')).toHaveCount(cls!.length + 1)
  await expect(page.getByTestId('sira-tablo').locator('tbody td.num b').first()).toContainText(/\d net$/)
  await expect(page.getByTestId('deneme-ort')).toContainText('Sınıf ortalaması (net)')
  // Analiz kapsamı: varsayılan bütün denemeler; "Son deneme" seçilince tabloda tek deneme sütunu kalır
  const kapsam = page.getByRole('group', { name: 'Analiz kapsamı' })
  await expect(kapsam.getByRole('button', { name: /^Tüm denemeler \(\d+\)$/ })).toHaveAttribute('aria-pressed', 'true')
  const tumSutun = await page.getByTestId('sira-tablo').locator('thead th').count()
  expect(tumSutun).toBeGreaterThan(2)
  await kapsam.getByRole('button', { name: 'Son deneme' }).click()
  await expect(page.getByTestId('sira-tablo').locator('thead th')).toHaveCount(2)
  // "Deneme seç": işaretlenen denemeler kadar sütun
  await kapsam.getByRole('button', { name: 'Deneme seç' }).click()
  const kutular = page.getByRole('group', { name: 'Analize girecek denemeler' }).getByRole('checkbox')
  await kutular.first().check()
  await expect(page.getByTestId('sira-tablo').locator('thead th')).toHaveCount(3)
  await kapsam.getByRole('button', { name: /^Tüm denemeler/ }).click()
  await expect(page.getByTestId('sira-tablo').locator('thead th')).toHaveCount(tumSutun)
  // Animasyon bitmeden ölçülen yarı saydam metin yanlış kontrast uyarısı verir (diğer testlerdeki gibi)
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.waitForTimeout(300)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa']).analyze()
  expect(axe.violations.filter((v) => v.impact === 'serious' || v.impact === 'critical').map((v) => v.id)).toEqual([])
  await shot(page, 'sinif-analizi')
  const dl = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PDF indir' }).click()
  expect((await dl).suggestedFilename()).toBe('sinif-analizi-8-B.pdf')
  await page.goBack()
  await expect(page.getByRole('button', { name: 'Sınıf analizi' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Sınıflar' })).toBeVisible()
})

test('veli ve öğrenci Sınıflar ve sınıf analizini görmez', async ({ page }) => {
  await login(page, ...DEMO.veli)
  await expect(page.getByRole('link', { name: 'Sınıflar', exact: true })).toHaveCount(0)
  await page.goto('/siniflar?gorunum=analiz')
  await expect(page.getByRole('heading', { name: /Sınıf analizi/ })).toHaveCount(0)
})

test('branş öğretmeni: Sınıflar yalnız derse girdiği şubeler ve kendi dersi; deneme netleri; sınıf analizi o dersten', async ({ page }) => {
  test.setTimeout(90_000)
  const svc = service()
  await login(page, ...DEMO.matematik)
  await page.getByRole('link', { name: 'Sınıflar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sınıflar' })).toBeVisible()
  // Şube seçici yalnız öğretmenin görebildiği öğrencilerin şubeleri (RLS 0023)
  const { data: prof } = await svc.from('profiles').select('id').eq('email', DEMO.matematik[0]).single()
  const { data: benim } = await svc.rpc('teacher_classes', { uid: prof!.id })
  const { data: siniflar } = await svc.from('classes').select('id, name')
  const adlar = (siniflar ?? []).filter((c) => (benim as string[]).includes(c.id)).map((c) => c.name)
  const baska = (siniflar ?? []).map((c) => c.name).filter((n) => !adlar.includes(n))
  const secici = page.locator('#clsPick').or(page.getByRole('group', { name: 'Şube' }))
  await expect(secici).toBeVisible()
  for (const n of baska) await expect(secici.getByText(n, { exact: true })).toHaveCount(0)
  // Yalnız kendi dersi
  await expect(page.getByRole('group', { name: 'Ders' }).getByRole('button')).toHaveText(['Matematik'])
  // Deneme netleri tablosu ve kapsam seçimi
  await expect(page.getByTestId('deneme-netleri').locator('tbody tr').first()).toBeVisible()
  const satir = await page.getByTestId('deneme-netleri').locator('tbody tr').count()
  await page.getByRole('group', { name: 'Analiz kapsamı' }).getByRole('button', { name: 'Son deneme' }).click()
  await expect(page.getByTestId('deneme-netleri').locator('tbody tr')).toHaveCount(1)
  expect(satir).toBeGreaterThan(1)
  await shot(page, 'siniflar-brans')
  // Sınıf analizi: başlıkta ders; puan yok, netler var
  await page.getByRole('button', { name: 'Sınıf analizi' }).click()
  await expect(page.getByRole('heading', { name: /Sınıf analizi · Matematik$/ })).toBeVisible()
  await expect(page.getByTestId('sira-tablo').locator('tbody td.num b').first()).toContainText(/\d net$/)
  await expect(page.getByTestId('sira-tablo')).not.toContainText('puan')
  await shot(page, 'sinif-analizi-brans')
})
